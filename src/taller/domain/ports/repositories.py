from taller.domain.enums import ClasificacionComprobante, EstadoComprobante


class EmpresaRepository(Protocol):
    def obtener(self, empresa_id: UUID) -> Empresa | None: ...
    def listar(
        self, *, q: str | None = None, incluir_archivados: bool = False
    ) -> list[Empresa]: ...
    def existe_cuit(self, cuit: str, *, excluir_id: UUID | None = None) -> bool: ...
    def guardar(self, empresa: Empresa) -> None: ...


class ClienteRepository(Protocol):
    def obtener(self, cliente_id: UUID) -> Cliente | None: ...
    def listar(
        self,
        *,
        q: str | None = None,
        empresa_id: UUID | None = None,
        incluir_archivados: bool = False,
    ) -> list[Cliente]: ...
    def guardar(self, cliente: Cliente) -> None: ...


